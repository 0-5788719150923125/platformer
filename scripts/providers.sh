#!/usr/bin/env bash
# Wire optional providers and their adapters into the current workspace.
#
# Terraform sets up every provider the configuration mentions, even for modules
# with count = 0, so a cloud that's merely available would force every user to
# hold its credentials. Instead, clouds beyond AWS are composed per workspace,
# before Terraform runs (see next/fully-connected.md).
#
# A workspace declares an optional provider in terraform.tfvars.<workspace> (or
# the base terraform.tfvars): a cloud by naming its profile (oci_profile =
# "DEFAULT"), anything else by enabling it (port_enabled = true). For each
# declared provider this script:
#   - links providers/<name>.tf and providers/<name>_override.tf into the root
#     as provider_<name>.tf and provider_<name>_override.tf
#   - wires each service's adapter (<service>/<name>/) by writing
#     <service>/adapter_<name>.tf and <service>/adapters_override.tf
# Providers the workspace doesn't declare are unwired, so they're never
# downloaded or set up. A provider is never unwired while the workspace still
# has resources under it: empty it first, then remove the declaration.
#
# Usage: terraform workspace select <name> && scripts/providers.sh
# The root guard (output "optional_providers" in providers.tf) fails the plan if you forget.

set -euo pipefail
cd "$(dirname "$0")/.."
shopt -s nullglob

ws=$(terraform workspace show)
ws_file="terraform.tfvars.${ws}"
[[ -f $ws_file ]] || ws_file=""

# Same rule as the workspaces module: the workspace file wins, else the base
# terraform.tfvars; commented-out lines don't count.
setting() { # file name -> "declared" | "off" | "" (not set in that file)
  local f=$1 name=$2
  [[ -n $f && -f $f ]] || return 0
  if grep -qE "^[[:space:]]*${name}_profile[[:space:]]*=[[:space:]]*\"[^\"]+\"" "$f"; then echo declared; return; fi
  if grep -qE "^[[:space:]]*${name}_enabled[[:space:]]*=[[:space:]]*true" "$f"; then echo declared; return; fi
  if grep -qE "^[[:space:]]*${name}_enabled[[:space:]]*=[[:space:]]*false" "$f"; then echo off; fi
}
declared() {
  local own; own=$(setting "$ws_file" "$1")
  [[ -n $own ]] || own=$(setting terraform.tfvars "$1")
  [[ $own == declared ]]
}

# Resources under a provider: its adapters (module.<name>) and any modules its
# provider file brings along (e.g. providers/port.tf -> module.portal)
has_state() {
  local modules=("$1") m
  while read -r m; do modules+=("$m"); done < <(grep -oE '^module "[^"]+"' "providers/$1.tf" | cut -d'"' -f2)
  local pattern; pattern=$(IFS='|'; echo "${modules[*]}")
  terraform state list 2>/dev/null | grep -qE "(^|\.)module\.(${pattern})(\[|\.)"
}

changed=0
link() {
  if [[ ! -L $2 || $(readlink "$2") != "$1" ]]; then ln -sfn "$1" "$2"; changed=1; fi
}
write() {
  if [[ ! -f $1 ]] || [[ $(cat "$1") != "$2" ]]; then printf '%s\n' "$2" > "$1"; changed=1; fi
}
remove() {
  if [[ -e $1 || -L $1 ]]; then rm -f "$1"; changed=1; fi
}

linked=()
for requirement in providers/*_override.tf; do
  cloud=$(basename "$requirement" _override.tf)
  if declared "$cloud"; then
    link "providers/${cloud}.tf" "provider_${cloud}.tf"
    link "providers/${cloud}_override.tf" "provider_${cloud}_override.tf"
    linked+=("$cloud")
  else
    if [[ -L provider_${cloud}.tf ]] && has_state "$cloud"; then
      echo "Refusing to unwire '${cloud}': workspace '${ws}' still has ${cloud} resources in state." >&2
      echo "Empty it first (remove them from the state fragments and apply), then run this again." >&2
      exit 1
    fi
    remove "provider_${cloud}.tf"
    remove "provider_${cloud}_override.tf"
  fi
done

# Services that accept adapters carry a committed adapters.tf (default: none wired)
for hook in */adapters.tf; do
  service=${hook%/adapters.tf}
  entries=""
  for cloud in "${linked[@]+"${linked[@]}"}"; do
    [[ -d $service/$cloud ]] || continue
    write "$service/adapter_${cloud}.tf" "# Generated by scripts/providers.sh - do not edit.
module \"${cloud}\" {
  source  = \"./${cloud}\"
  config  = lookup(local.adapter_config, \"${cloud}\", {})
  context = local.adapter_context
}"
    entries+="    ${cloud} = module.${cloud}"$'\n'
  done
  for generated in "$service"/adapter_*.tf; do
    cloud=$(basename "$generated" .tf)
    cloud=${cloud#adapter_}
    [[ " ${linked[*]+"${linked[*]}"} " == *" ${cloud} "* ]] || remove "$generated"
  done
  if [[ -n $entries ]]; then
    write "$service/adapters_override.tf" "# Generated by scripts/providers.sh - do not edit.
locals {
  adapters = {
${entries}  }
}"
  else
    remove "$service/adapters_override.tf"
  fi
done

echo "workspace '${ws}': optional providers [ ${linked[*]+"${linked[*]}"} ]"
if (( changed )); then
  if ! out=$(terraform init -input=false -no-color 2>&1); then
    echo "$out" >&2
    exit 1
  fi
  echo "terraform init (provider set changed)"
fi
